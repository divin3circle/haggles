  key_revoked: { status: 401, title: "API key revoked or expired" },
  unauthorized: { status: 401, title: "Unauthorized" },
  forbidden: { status: 403, title: "Forbidden" },
  not_found: { status: 404, title: "Not found" },
  already_redeemed: { status: 409, title: "Payment already redeemed" },
  amount_mismatch: { status: 409, title: "Payment amount mismatch" },
  request_mismatch: { status: 409, title: "Request method or URL mismatch" },
  token_expired: { status: 410, title: "Payment token expired" },
  refund_not_allowed: { status: 409, title: "Refund not allowed" },
  idempotency_conflict: { status: 422, title: "Idempotency key conflict" },
