/**
 * Metadata entry for a catalogue error code (SPEC.md Appendix A).
 *
 * @example
 * ```ts
 * const entry: ErrorCatalogueEntry = ERROR_CATALOGUE.insufficient_funds;
 * ```
 */
export interface ErrorCatalogueEntry {
  /** Default HTTP status code returned for this error */
  readonly status: number;
  /** Short human-readable summary matching RFC 9457 `title` */
  readonly title: string;
}

