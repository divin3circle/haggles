/**
 * RFC 9457 `application/problem+json` response body returned by the facilitator (SPEC.md section 4.11).
 *
 * @example
 * ```ts
 * const problem: ProblemDetails = {
 *   type: "https://docs.haggles.example.com/errors/insufficient_funds",
 *   title: "Insufficient funds",
 *   status: 409,
 *   code: "insufficient_funds",
 *   detail: "Available balance 0.01 is less than 0.02.",
 *   request_id: "req_01J9Z3K4M5N6P7Q8R9S0T1U2V3",
 * };
 * ```
 */
export interface ProblemDetails {
  /** URI reference that identifies the problem type */
  type: string;
  /** Short, human-readable summary of the problem type */
  title: string;
  /** HTTP status code generated by the origin server */
  status: number;
  /** Machine-readable Haggles error code (Appendix A) */
  code: HagglesErrorCode;
  /** Human-readable explanation specific to this occurrence */
  detail: string;
  /** Request correlation ID (`req_...`) */
  request_id?: string | undefined;
}

/**
 * Options for constructing a {@link HagglesError}.
 *
 * @example
 * ```ts
 * const opts: HagglesErrorOptions = { code: "insufficient_funds", status: 409 };
 * ```
 */
export interface HagglesErrorOptions {
  /** Machine-readable error code */
  code: HagglesErrorCode;
  /** Optional HTTP status code */
  status?: number | undefined;
  /** Optional facilitator request ID (`req_...`) */
  requestId?: string | undefined;
  /** Optional underlying cause */
  cause?: unknown;
}

/**
 * Base error class for all Haggles SDK and protocol errors (SPEC.md section 10.1).
 *
 * @example
 * ```ts
 * throw new HagglesError("Available balance 0.01 is less than 0.02.", {
 *   code: "insufficient_funds",
 *   status: 409,
 * });
 * ```
 */
export class HagglesError extends Error {
  /** Machine-readable Haggles error code */
  readonly code: HagglesErrorCode;
  /** HTTP status code associated with the error, if applicable */
  readonly status?: number | undefined;
  /** Request ID returned by the facilitator, if applicable */
  readonly requestId?: string | undefined;

  constructor(message: string, options: HagglesErrorOptions) {
    super(message, options.cause !== undefined ? { cause: options.cause } : undefined);
    this.name = new.target.name;
    this.code = options.code;
    this.status = options.status ?? ERROR_CATALOGUE[options.code]?.status;
    this.requestId = options.requestId;
    Object.setPrototypeOf(this, new.target.prototype);
  }
}

/**
 * Thrown when a money string or micro-dollar value fails validation (SPEC.md section 10.1).
 *
 * @example
 * ```ts
 * throw new InvalidMoneyError("Amount must match ^\\d{1,7}(\\.\\d{1,6})?$");
 * ```
 */
export class InvalidMoneyError extends HagglesError {
  constructor(message: string, options?: { requestId?: string | undefined; cause?: unknown }) {
    super(message, {
      code: "invalid_money",
      status: 422,
      requestId: options?.requestId,
      cause: options?.cause,
    });
  }
}

