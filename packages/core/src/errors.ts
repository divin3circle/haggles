/**
 * Converts an RFC 9457 {@link ProblemDetails} object into the corresponding typed {@link HagglesError} subclass.
 *
 * @param problem - Parsed RFC 9457 problem response from the facilitator
 * @returns A typed {@link HagglesError} instance preserving `code`, `status`, and `requestId`
 *
 * @example
 * ```ts
 * const err = fromProblemDetails({
 *   type: "https://docs.haggles.example.com/errors/insufficient_funds",
 *   title: "Insufficient funds",
 *   status: 409,
 *   code: "insufficient_funds",
 *   detail: "Available balance 0.01 is less than 0.02.",
 *   request_id: "req_01J9Z3K4M5N6P7Q8R9S0T1U2V3",
 * });
 * console.log(err instanceof InsufficientFundsError); // true
 * ```
 */
export function fromProblemDetails(problem: ProblemDetails): HagglesError {
  const opts = { requestId: problem.request_id };
  switch (problem.code) {
    case "invalid_money":
      return new InvalidMoneyError(problem.detail, opts);
    case "invalid_challenge":
      return new InvalidChallengeError(problem.detail, opts);
    case "challenge_mismatch":
      return new ChallengeMismatchError(problem.detail, opts);
    case "policy_violation":
      return new PolicyViolationError(problem.detail, opts);
    case "insufficient_funds":
      return new InsufficientFundsError(problem.detail, opts);
    case "payment_not_accepted":
      return new PaymentNotAcceptedError(problem.detail, opts);
    case "non_replayable_body":
      return new NonReplayableBodyError(problem.detail, opts);
    case "facilitator_unavailable":
      return new FacilitatorUnavailableError(problem.detail, opts);
    default:
      return new HagglesError(problem.detail, {
        code: problem.code,
        status: problem.status,
        requestId: problem.request_id,
      });
  }
}
